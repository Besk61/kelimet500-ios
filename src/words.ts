export function normalizeTurkish(value: string): string {
  return value.trim().toLocaleUpperCase('tr-TR');
}

export function foldTurkish(value: string): string {
  return normalizeTurkish(value).replaceAll('İ', 'I');
}

export const allowedWordList = Array.from(new Set(
  rawAllowedWords.split(/\s+/).map(normalizeTurkish).filter(word => [...word].length === 5)
));

export const allowedWords = new Set(allowedWordList.map(foldTurkish));

export const solutionWords = Array.from(new Set(
  rawSolutionWords.split(/\s+/).map(normalizeTurkish).filter(word => [...word].length === 5)
));

export function isAllowedWord(word: string): boolean {
  return allowedWords.has(foldTurkish(word)) || solutionWords.some(item => foldTurkish(item) === foldTurkish(word));
}
